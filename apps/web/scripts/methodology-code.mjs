#!/usr/bin/env node
/*
 * Writes app/metodologie/score-code.generated.ts: the risk score's source files as /metodologie shows them (owner,
 * 9 November 2026: the page shows the code itself instead of linking to the repository). The page is rendered on the
 * server at request time, where the monorepo's source files are not in the image, so the text ships as a module.
 * Run `pnpm --filter web methodology-code` after changing either file; score-code.test.ts fails until then.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(web, "../..");
const FILES = [
  { id: "cod-formula", title: "Formula și pragurile", path: "packages/db/src/profile-flags.ts" },
  { id: "cod-profiluri", title: "Calculul pe profiluri", path: "apps/ingestion/src/flags/score.ts" },
];

const entries = FILES.map((f) => ({ ...f, source: readFileSync(join(root, f.path), "utf8") }));
const out = `// Generated by apps/web/scripts/methodology-code.mjs from the files named in \`path\`. Do not edit:
// run \`pnpm --filter web methodology-code\` after changing them (score-code.test.ts checks they match).
export const SCORE_CODE: readonly { id: string; title: string; path: string; source: string }[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(web, "app/metodologie/score-code.generated.ts"), out);
console.log(`score-code.generated.ts: ${entries.map((e) => `${e.path} (${e.source.split("\n").length} lines)`).join(", ")}`);
